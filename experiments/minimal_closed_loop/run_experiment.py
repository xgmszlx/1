from __future__ import annotations

import argparse
import json
from pathlib import Path

import matplotlib.pyplot as plt
import numpy as np
import pandas as pd

from simulator import (
    GridWorld,
    SimConfig,
    fused_risk_map,
    lidar_health_map,
    load_sdf_box_world,
    run_simulation,
    visual_health_map,
)


POLICIES = ["nearest", "information_gain", "distance_advantage", "visual_risk", "cross_modal_risk"]
SCENARIOS = ["visual_degradation", "complementary", "common_mode"]


def parse_seeds(spec: str) -> list[int]:
    if ":" in spec:
        start, stop = (int(v) for v in spec.split(":", 1))
        return list(range(start, stop))
    return [int(v) for v in spec.split(",")]


def plot_world(world: GridWorld, visual: np.ndarray, lidar: np.ndarray, risk: np.ndarray, out: Path) -> None:
    fig, axes = plt.subplots(1, 4, figsize=(15, 4), constrained_layout=True)
    panels = [(world.occupancy, "Occupancy"), (visual, "Visual health"), (lidar, "2-D LiDAR health"), (risk, "Fused risk")]
    for ax, (field, title) in zip(axes, panels):
        im = ax.imshow(field, origin="lower", cmap="viridis")
        ax.set_title(title)
        ax.set_axis_off()
        fig.colorbar(im, ax=ax, fraction=0.046)
    fig.savefig(out, dpi=180)
    plt.close(fig)


def plot_tradeoff(df: pd.DataFrame, out: Path) -> None:
    summary = df.groupby(["scenario", "policy"], as_index=False).agg(path_m=("path_m", "mean"), pose_rmse_m=("pose_rmse_m", "mean"), failures=("failure_steps", "mean"))
    fig, axes = plt.subplots(1, len(SCENARIOS), figsize=(15, 4.5), constrained_layout=True)
    for ax, scenario in zip(axes, SCENARIOS):
        part = summary[summary.scenario == scenario]
        ax.scatter(part.path_m, part.pose_rmse_m, s=55)
        for row in part.itertuples():
            ax.annotate(row.policy.replace("_", "\n"), (row.path_m, row.pose_rmse_m), fontsize=7, xytext=(4, 4), textcoords="offset points")
        ax.set_title(scenario)
        ax.set_xlabel("Mean path length [m]")
        ax.set_ylabel("Mean pose RMSE proxy [m]")
        ax.grid(alpha=0.25)
    fig.savefig(out, dpi=180)
    plt.close(fig)


def write_summary(df: pd.DataFrame, out: Path) -> None:
    metrics = ["complete", "coverage", "path_m", "pose_rmse_m", "max_pose_error_m", "risk_exposure", "failure_steps", "stabilization_revisits", "recovery_budget_spent_m"]
    grouped = df.groupby(["scenario", "policy"])[metrics].agg(["mean", "std"])
    lines = [
        "# Minimum experiment results",
        "",
        "These numbers are generated by a synthetic localization-error proxy. They are suitable for mechanism falsification, not a paper performance claim.",
        "",
    ]
    for scenario in SCENARIOS:
        lines += [f"## {scenario}", "", "```text", grouped.loc[scenario].round(4).to_string(), "```", ""]
    out.write_text("\n".join(lines), encoding="utf-8")


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--seeds", default="0:10")
    parser.add_argument("--output", type=Path, default=Path(__file__).parent / "results")
    parser.add_argument("--stabilization-threshold", type=float, default=0.75)
    parser.add_argument("--recovery-budget-m", type=float, default=16.0)
    args = parser.parse_args()
    args.output.mkdir(parents=True, exist_ok=True)
    config = SimConfig(
        stabilization_threshold=args.stabilization_threshold,
        recovery_detour_budget_m=args.recovery_budget_m,
    )

    root = Path(__file__).resolve().parents[2]
    sdf = root / "projects/autonomous-exploration-demo-benchmark/simulation/worlds/corridor/corridor.world"
    world = load_sdf_box_world(sdf)
    lidar = lidar_health_map(world)
    visual = visual_health_map(world, "complementary")
    risk = fused_risk_map(world, visual, lidar, "complementary")
    plot_world(world, visual, lidar, risk, args.output / "health_maps.png")

    records = []
    raw_results = []
    health_by_scenario = {}
    for scenario in SCENARIOS:
        scenario_visual = visual_health_map(world, scenario)
        # In the single-modality trial, laser geometry is deliberately kept
        # informative. The complementary trial retains the geometry-derived
        # low-health regions, and common_mode adds a shared degradation zone.
        scenario_lidar = lidar.copy()
        if scenario == "visual_degradation":
            scenario_lidar[world.occupancy == 0] = np.maximum(
                scenario_lidar[world.occupancy == 0], 0.78
            )
        health_by_scenario[scenario] = (
            scenario_visual,
            scenario_lidar,
            fused_risk_map(world, scenario_visual, scenario_lidar, scenario),
        )

    for scenario in SCENARIOS:
        for policy in POLICIES:
            for seed in parse_seeds(args.seeds):
                result = run_simulation(world, policy, seed, scenario, config, health_by_scenario[scenario])
                records.append({"scenario": scenario, **result.as_dict()})
                raw_results.append(result)
    df = pd.DataFrame(records)
    df.to_csv(args.output / "trials.csv", index=False)
    (args.output / "trials.json").write_text(json.dumps(records, indent=2), encoding="utf-8")
    write_summary(df, args.output / "summary.md")
    plot_tradeoff(df, args.output / "tradeoff.png")

    # Plot one deterministic trajectory per policy for the complementary case.
    fig, axes = plt.subplots(1, len(POLICIES), figsize=(17, 4), constrained_layout=True)
    for ax, policy in zip(axes, POLICIES):
        result = next(r for r in raw_results if r.policy == policy and r.seed == parse_seeds(args.seeds)[0])
        ax.imshow(world.occupancy, origin="lower", cmap="gray_r")
        path = np.asarray(result.trajectory)
        ax.plot(path[:, 1], path[:, 0], linewidth=0.7)
        ax.set_title(f"{policy}\n{result.path_m:.1f} m, RMSE {result.pose_rmse_m:.2f}")
        ax.set_axis_off()
    fig.savefig(args.output / "trajectories.png", dpi=180)
    plt.close(fig)

    print(df.groupby(["scenario", "policy"])[["coverage", "path_m", "pose_rmse_m", "failure_steps"]].mean().round(4).to_string())


if __name__ == "__main__":
    main()
